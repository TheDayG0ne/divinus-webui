'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const readme = read('README.md');
const page = read('www/index.html');
const script = read('www/a/divinus.js');
assert(readme.includes('/api/cameras'));
assert(readme.includes('status: unknown'));
assert(readme.includes('web_enable_static'));
assert(readme.includes('POST /setup'));
assert(page.includes('href="/image.jpg"'));
assert(script.includes("fetch(path, { credentials: 'same-origin'"));
assert(!/https?:\/\/|\.port\s*=|cameraOrigin/.test(script));
assert(!/id="(?:isp-form|audio-form|preview-toggle)"/.test(page));
assert(!/proxy_pass|proxy_set_header/i.test(readme));
console.log('Divinus frontend contract checks passed');
